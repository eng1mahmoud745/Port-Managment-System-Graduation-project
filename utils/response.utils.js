/**
 * مسؤولية الملف: توفير دوال خفيفة وموحدة لإرسال استجابات النجاح والخطأ من دون تغيير شكل الـ JSON النهائي.
 * ملاحظات: هذا الملف لا يفرض بنية جديدة على الاستجابة، بل يمرر الجسم كما هو لتقليل المخاطر أثناء التطبيق التدريجي.
 */

/**
 * الغرض: إرسال استجابة نجاح بنفس جسم JSON الذي يحدده المستدعي.
 * المدخلات: res كائن الاستجابة من Express، statusCode كود الحالة المطلوب، body الجسم النهائي الذي سيصل للواجهة.
 * المخرجات: يرسل استجابة HTTP ناجحة إلى العميل ويعيد كائن الاستجابة من Express.
 * الآثار الجانبية: يكتب مباشرة إلى الاستجابة الحالية عبر res.status(...).json(...).
 * ملاحظات: لا يضيف حقولًا تلقائيًا مثل success أو data، حتى يبقى شكل الاستجابة مطابقًا للكود الحالي.
 */
function successResponse(res, statusCode, body) {
    return res.status(statusCode).json(body);
}

/**
 * الغرض: إرسال استجابة خطأ بنفس جسم JSON الذي يحدده المستدعي.
 * المدخلات: res كائن الاستجابة من Express، statusCode كود الخطأ، body الجسم النهائي الذي سيصل للواجهة.
 * المخرجات: يرسل استجابة HTTP خطأ إلى العميل ويعيد كائن الاستجابة من Express.
 * الآثار الجانبية: يكتب مباشرة إلى الاستجابة الحالية عبر res.status(...).json(...).
 * ملاحظات: لا يعيد تشكيل رسالة الخطأ أو أسماء الحقول، ولذلك يمكن استخدامه تدريجيًا من دون كسر الواجهات الحالية.
 */
function errorResponse(res, statusCode, body) {
    return res.status(statusCode).json(body);
}

module.exports = {
    successResponse,
    errorResponse
};
